"""Artifact records use strings so they survive Spikee JSONL serialization."""

import hashlib
import json
import re
from pathlib import Path

PREFIX = "SPIKEE_DOCUMENT_V1:"


def read_plugin_config(option_string, allowed):
    """Read a JSON config with CLI overrides using standard Spikee options."""
    from spikee.utilities.modules import parse_options

    cli = parse_options(option_string)
    options = {}
    if cli.get("config"):
        options = json.loads(Path(cli["config"]).read_text(encoding="utf-8"))
        if not isinstance(options, dict):
            raise ValueError("Plugin config must be a JSON object")
    options.update(cli)
    unknown = set(options) - allowed - {"config"}
    if unknown:
        raise ValueError(f"Unknown plugin options: {sorted(unknown)}")
    return options


def encode(record):
    return PREFIX + json.dumps(record, ensure_ascii=True)


def inspect_record(content):
    if not isinstance(content, str) or not content.startswith(PREFIX):
        raise ValueError(
            "Expected a document_forge artifact record generated by Spikee"
        )
    record = json.loads(content[len(PREFIX) :])
    if not isinstance(record, dict) or record.get("version") != 1:
        raise ValueError("Unsupported document artifact record version")
    if not isinstance(record.get("generated_file"), str) or not isinstance(
        record.get("artifact_sha256"), str
    ):
        raise ValueError(  # noqa: TRY004 - malformed serialized record
            "Document artifact record requires a file path and SHA-256 hash"
        )
    path = Path(record["generated_file"])
    if not path.is_file() or sha256_file(path) != record["artifact_sha256"]:
        raise ValueError(
            "Generated artifact is missing or has changed; regenerate the dataset"
        )
    return f"Validated document artifact: {path}", record


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def safe_name(value: str) -> str:
    result = re.sub(r"[^A-Za-z0-9._-]+", "-", value).strip("-_")
    return result or "document"
